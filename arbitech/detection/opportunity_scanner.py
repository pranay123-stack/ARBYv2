class ScannerEventType(str, Enum):
    """Types of scanner events."""
    SCAN_STARTED = "scan_started"
    SCAN_COMPLETED = "scan_completed"
    SCAN_FAILED = "scan_failed"
    OPPORTUNITY_FOUND = "opportunity_found"
    BOOKMAKER_UNAVAILABLE = "bookmaker_unavailable"
    VLM_ERROR = "vlm_error"
    CIRCUIT_BREAKER_OPEN = "circuit_breaker_open"


@dataclass
class ScannerEvent:
    """Event generated by the opportunity scanner."""
    event_type: ScannerEventType
    timestamp: datetime
    bookmaker: Optional[str] = None
    sport: Optional[Sport] = None
    opportunity_id: Optional[UUID] = None
    error_message: Optional[str] = None
    metadata: Optional[Dict[str, Any]] = None


class ScanMetrics:
    """Metrics for scanner performance tracking."""
    
    def __init__(self):
        self.total_scans = 0
        self.successful_scans = 0
        self.failed_scans = 0
        self.opportunities_found = 0
        self.vlm_api_calls = 0
        self.vlm_success_calls = 0
        self.average_scan_time = 0.0
        self.last_scan_at: Optional[datetime] = None
        self.errors_by_category: Dict[str, int] = {}
        
    def to_dict(self) -> Dict[str, Any]:
        """Convert metrics to dictionary."""
        return {
            "total_scans": self.total_scans,
            "successful_scans": self.successful_scans,
            "failed_scans": self.failed_scans,
            "success_rate": self.successful_scans / max(self.total_scans, 1),
            "opportunities_found": self.opportunities_found,
            "vlm_api_calls": self.vlm_api_calls,
            "vlm_success_rate": self.vlm_success_calls / max(self.vlm_api_calls, 1),
            "average_scan_time": self.average_scan_time,
            "last_scan_at": self.last_scan_at.isoformat() if self.last_scan_at else None,
            "errors_by_category": self.errors_by_category
        }


