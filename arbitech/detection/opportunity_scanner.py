async def create_scanner(
    config: Optional[Dict[str, Any]] = None,
    session_name: str = "Default Scanner"
) -> OpportunityScanner:
    """
    Create and configure an opportunity scanner.
    
    Args:
        config: Optional configuration override
        session_name: Name for the scanner session
        
    Returns:
        Configured OpportunityScanner instance
    """
    scanner = OpportunityScanner(config)
    
    # Add default event handlers
    scanner.add_event_handler(_default_event_handler)
    
    return scanner


async def _default_event_handler(event: ScannerEvent):
    """Default event handler for logging and basic processing."""
    logger = logging.getLogger(__name__)
    
    if event.event_type == ScannerEventType.OPPORTUNITY_FOUND:
        logger.info(
            "🎯 Arbitrage opportunity found! ID: %s, Bookmaker: %s, Sport: %s",
            event.opportunity_id,
            event.bookmaker,
            event.sport.value if event.sport else "unknown"
        )
    elif event.event_type == ScannerEventType.VLM_ERROR:
        logger.warning(
            "VLM extraction error for %s (%s): %s",
            event.bookmaker,
            event.sport.value if event.sport else "unknown",
            event.error_message
        )
    elif event.event_type == ScannerEventType.SCAN_FAILED:
        logger.error(
            "Scan failed for %s (%s): %s",
            event.bookmaker,
            event.sport.value if event.sport else "unknown",
            event.error_message
        )


