class OpportunityScanner:
    """
    Main scanner class that coordinates VLM extraction, monitors multiple bookmaker interfaces,
    and detects arbitrage opportunities in real-time.
    """
    
    def __init__(
        self, 
        config: Optional[Dict[str, Any]] = None,
        session_id: Optional[UUID] = None
    ):
        """
        Initialize the opportunity scanner.
        
        Args:
            config: Optional configuration override
            session_id: Optional session identifier
        """
        self.config = config or {}
        self.session_id = session_id or uuid4()
        self.logger = logging.getLogger(__name__)
        
        # Get scanner configuration
        self.scanner_config = self.config.get('scanner', {})
        self.max_concurrent_scans = self.scanner_config.get('max_concurrent_scans', 10)
        self.min_profit_margin = Decimal(str(self.scanner_config.get('min_profit_margin', 2.0)))
        self.max_scan_age_seconds = self.scanner_config.get('max_scan_age_seconds', 300)
        self.retry_failed_scans = self.scanner_config.get('retry_failed_scans', True)
        self.max_retries = self.scanner_config.get('max_retries', 3)
        
        # Initialize components
        self._initialize_components()
        
        # Scanner state
        self.status = ScannerStatus.IDLE
        self.started_at: Optional[datetime] = None
        self.metrics = ScanMetrics()
        self.event_handlers: List[Callable[[ScannerEvent], None]] = []
        self.active_scans: Dict[UUID, ScanTask] = {}
        
        # Bookmaker configuration
        self.bookmaker_configs = self._load_bookmaker_configs()
        self.active_bookmakers = self._get_active_bookmakers()
        
        self.logger.info("OpportunityScanner initialized with session ID: %s", self.session_id)
    
    def _initialize_components(self):
        """Initialize scanner components."""
        try:
            # Initialize VLM extractor
            self.vlm_extractor = OddsExtractor(self.config.get('vlm', {}))
            
            # Initialize scanner engine
            engine_config = {
                'max_concurrent_scans': self.max_concurrent_scans,
                'retry_failed_scans': self.retry_failed_scans,
                'max_retries': self.max_retries
            }
            self.scanner_engine = ScannerEngine(engine_config)
            
            # Initialize market monitor
            self.market_monitor = MarketMonitor(self.config.get('market_monitor', {}))
            
            # Initialize scan scheduler
            scheduler_config = self.config.get('scheduler', {})
            self.scan_scheduler = ScanScheduler(scheduler_config)
            
            self.logger.info("Scanner components initialized successfully")
            
        except Exception as e:
            self.logger.error("Failed to initialize scanner components: %s", str(e))
            raise
    
    def _load_bookmaker_configs(self) -> Dict[str, Dict[str, Any]]:
        """Load bookmaker configurations."""
        bookmaker_config = get_config('bookmakers', {})
        return {name: config for name, config in bookmaker_config.items() if config.get('enabled', False)}
    
    def _get_active_bookmakers(self) -> List[str]:
        """Get list of active bookmakers."""
        return list(self.bookmaker_configs.keys())
    
    async def start_scanning(
        self, 
        sports: Optional[List[Sport]] = None,
        custom_schedule: Optional[Dict[str, Any]] = None
    ) -> bool:
        """
        Start the opportunity scanner.
        
        Args:
            sports: List of sports to scan (None for all enabled)
            custom_schedule: Custom scheduling configuration
            
        Returns:
            True if scanning started successfully
        """
        try:
            if self.status != ScannerStatus.IDLE:
                self.logger.warning("Scanner already running with status: %s", self.status.value)
                return False
            
            self.status = ScannerStatus.SCANNING
            self.started_at = datetime.now(timezone.utc)
            
            # Configure which sports to scan
            if sports is None:
                sports = self._get_enabled_sports()
            
            self.logger.info("Starting opportunity scanner for sports: %s", [s.value for s in sports])
            
            # Set up scan schedules
            if custom_schedule:
                self.scan_scheduler.update_config(custom_schedule)
            
            # Start scanner components
            await self._start_components()
            
            # Register event handlers
            self._register_event_handlers()
            
            # Start monitoring loop
            asyncio.create_task(self._monitoring_loop())
            
            self.logger.info("Opportunity scanner started successfully")
            return True
            
        except Exception as e:
            self.logger.error("Failed to start opportunity scanner: %s", str(e))
            self.status = ScannerStatus.ERROR
            return False
    
    async def stop_scanning(self) -> bool:
        """Stop the opportunity scanner."""
        try:
            if self.status == ScannerStatus.IDLE:
                self.logger.warning("Scanner is not running")
                return True
            
            self.logger.info("Stopping opportunity scanner...")
            
            self.status = ScannerStatus.STOPPED
            
            # Cancel active scans
            for scan_id in list(self.active_scans.keys()):
                await self._cancel_scan(scan_id)
            
            # Stop components
            await self._stop_components()
            
            self.logger.info("Opportunity scanner stopped")
            return True
            
        except Exception as e:
            self.logger.error("Error stopping opportunity scanner: %s", str(e))
            return False
    
    def add_event_handler(self, handler: Callable[[ScannerEvent], None]):
        """Add an event handler for scanner events."""
        self.event_handlers.append(handler)
    
    def get_status(self) -> Dict[str, Any]:
        """Get current scanner status."""
        return {
            "session_id": str(self.session_id),
            "status": self.status.value,
            "started_at": self.started_at.isoformat() if self.started_at else None,
            "active_scans": len(self.active_scans),
            "active_bookmakers": len(self.active_bookmakers),
            "metrics": self.metrics.to_dict(),
            "uptime_minutes": (
                (datetime.now(timezone.utc) - self.started_at).total_seconds() / 60
                if self.started_at else 0
            )
        }
    
    def get_opportunities(
        self, 
        min_profit_margin: Optional[Decimal] = None,
        sport: Optional[Sport] = None,
        risk_tier: Optional[RiskTier] = None,
        limit: int = 100
    ) -> List[ArbitrageOpportunity]:
        """Get discovered arbitrage opportunities."""
        return self.market_monitor.get_opportunities(
            min_profit_margin=min_profit_margin,
            sport=sport,
            risk_tier=risk_tier,
            limit=limit
        )
    
    async def scan_bookmaker(
        self, 
        bookmaker: str, 
        sport: Sport,
        image_data: Union[str, bytes],
        market_type: str = "match_winner",
        event_name: str = ""
    ) -> Optional[ArbitrageOpportunity]:
        """
        Scan a specific bookmaker for arbitrage opportunities.
        
        Args:
            bookmaker: Bookmaker name
            sport: Sport type
            image_data: Image data (URL or bytes)
            market_type: Market type
            event_name: Event name
            
        Returns:
            ArbitrageOpportunity if found, None otherwise
        """
        try:
            self.logger.debug("Scanning %s for %s", bookmaker, sport.value)
            
            # Create extraction request
            request = ExtractionRequest(
                image_data=image_data,
                bookmaker=bookmaker,
                sport=sport,
                market_type=market_type,
                event_name=event_name or f"{sport.value} match",
                min_confidence=0.7
            )
            
            # Extract odds using VLM
            result = await self.vlm_extractor.extract_odds(request)
            
            # Update metrics
            self.metrics.vlm_api_calls += 1
            if result.success:
                self.metrics.vlm_success_calls += 1
            
            if not result.success:
                self.logger.warning("VLM extraction failed for %s: %s", bookmaker, result.error_message)
                await self._emit_event(
                    ScannerEventType.VLM_ERROR,
                    bookmaker=bookmaker,
                    sport=sport,
                    error_message=result.error_message
                )
                return None
            
            # Store odds in market monitor
            odds_data = {
                'bookmaker': bookmaker,
                'sport': sport,
                'market_type': market_type,
                'odds': result.extracted_odds,
                'event_outcomes': result.event_outcomes,
                'confidence': result.confidence.overall,
                'extracted_at': result.extracted_at,
                'metadata': {
                    'extraction_id': str(result.id),
                    'vlm_model_used': result.metadata.vlm_model_used,
                    'template_used': result.metadata.template_used
                }
            }
            
            # Update market state
            market_updated = await self.market_monitor.update_market_odds(odds_data)
            
            # Check for arbitrage opportunities
            if market_updated:
                opportunities = await self.market_monitor.find_arbitrage_opportunities(
                    min_profit_margin=self.min_profit_margin
                )
                
                if opportunities:
                    opportunity = opportunities[0]  # Return the best opportunity
                    self.metrics.opportunities_found += 1
                    
                    await self._emit_event(
                        ScannerEventType.OPPORTUNITY_FOUND,
                        bookmaker=bookmaker,
                        sport=sport,
                        opportunity_id=opportunity.id
                    )
                    
                    return opportunity
            
            return None
            
        except Exception as e:
            self.logger.error("Error scanning %s: %s", bookmaker, str(e))
            await self._emit_event(
                ScannerEventType.SCAN_FAILED,
                bookmaker=bookmaker,
                sport=sport,
                error_message=str(e)
            )
            return None
    
    async def _start_components(self):
        """Start all scanner components."""
        # Start scanner engine
        await self.scanner_engine.start()
        
        # Start market monitor
        await self.market_monitor.start()
        
        # Start scan scheduler
        await self.scan_scheduler.start()
        
        self.logger.info("All scanner components started")
    
    async def _stop_components(self):
        """Stop all scanner components."""
        # Stop components gracefully
        if hasattr(self, 'scan_scheduler'):
            await self.scan_scheduler.stop()
        
        if hasattr(self, 'market_monitor'):
            await self.market_monitor.stop()
        
        if hasattr(self, 'scanner_engine'):
            await self.scanner_engine.stop()
        
        self.logger.info("All scanner components stopped")
    
    def _register_event_handlers(self):
        """Register event handlers for scanner components."""
        # Market monitor events
        self.market_monitor.add_event_handler(self._handle_market_event)
        
        # Scanner engine events
        self.scanner_engine.add_event_handler(self._handle_engine_event)
    
    async def _handle_market_event(self, event: MarketEvent):
        """Handle market monitor events."""
        if event.event_type == MarketEvent.ARBITRAGE_DETECTED:
            self.metrics.opportunities_found += 1
            await self._emit_event(
                ScannerEventType.OPPORTUNITY_FOUND,
                metadata={'market_event': event.to_dict()}
            )
    
    async def _handle_engine_event(self, event: Any):
        """Handle scanner engine events."""
        # Handle scanner engine events
        self.logger.debug("Received engine event: %s", event)
    
    async def _monitoring_loop(self):
        """Main monitoring loop for the scanner."""
        try:
            while self.status == ScannerStatus.SCANNING:
                # Update metrics
                await self._update_metrics()
                
                # Check component health
                health_ok = await self._check_component_health()
                
                if not health_ok:
                    self.logger.warning("Component health check failed")
                    # Could implement automatic recovery here
                
                # Clean up old scans
                await self._cleanup_old_scans()
                
                # Sleep before next iteration
                await asyncio.sleep(10)  # Check every 10 seconds
                
        except Exception as e:
            self.logger.error("Error in monitoring loop: %s", str(e))
            self.status = ScannerStatus.ERROR
    
    async def _update_metrics(self):
        """Update scanner metrics."""
        # Update average scan time
        if self.active_scans:
            total_time = sum(scan.elapsed_time for scan in self.active_scans.values())
            self.metrics.average_scan_time = total_time / len(self.active_scans)
        
        self.metrics.last_scan_at = datetime.now(timezone.utc)
    
    async def _check_component_health(self) -> bool:
        """Check health of all components."""
        try:
            # Check VLM extractor
            if not await self.vlm_extractor.health_check():
                return False
            
            # Check other components
            # Add health checks for other components as needed
            
            return True
            
        except Exception as e:
            self.logger.error("Health check failed: %s", str(e))
            return False
    
    async def _cleanup_old_scans(self):
        """Clean up old completed scans."""
        current_time = datetime.now(timezone.utc)
        completed_scans = [
            scan_id for scan_id, scan in self.active_scans.items()
            if scan.status.value in ['completed', 'failed'] and
            (current_time - scan.created_at).total_seconds() > self.max_scan_age_seconds
        ]
        
        for scan_id in completed_scans:
            del self.active_scans[scan_id]
    
    async def _cancel_scan(self, scan_id: UUID):
        """Cancel an active scan."""
        if scan_id in self.active_scans:
            scan = self.active_scans[scan_id]
            await self.scanner_engine.cancel_scan(scan_id)
            del self.active_scans[scan_id]
    
    def _get_enabled_sports(self) -> List[Sport]:
        """Get list of enabled sports for scanning."""
        # Get all sports from Sport enum
        enabled_sports = list(Sport)
        
        # Filter based on configuration
        sports_config = self.scanner_config.get('sports', {})
        if 'whitelist' in sports_config:
            enabled_sports = [s for s in enabled_sports if s.value in sports_config['whitelist']]
        elif 'blacklist' in sports_config:
            enabled_sports = [s for s in enabled_sports if s.value not in sports_config['blacklist']]
        
        return enabled_sports
    
    async def _emit_event(
        self, 
        event_type: ScannerEventType, 
        bookmaker: Optional[str] = None,
        sport: Optional[Sport] = None,
        opportunity_id: Optional[UUID] = None,
        error_message: Optional[str] = None,
        metadata: Optional[Dict[str, Any]] = None
    ):
        """Emit a scanner event."""
        event = ScannerEvent(
            event_type=event_type,
            timestamp=datetime.now(timezone.utc),
            bookmaker=bookmaker,
            sport=sport,
            opportunity_id=opportunity_id,
            error_message=error_message,
            metadata=metadata
        )
        
        # Call all registered handlers
        for handler in self.event_handlers:
            try:
                handler(event)
            except Exception as e:
                self.logger.error("Error in event handler: %s", str(e))


