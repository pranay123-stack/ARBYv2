class MarketEventType(str, Enum):
    """Types of market events."""
    ODDS_UPDATED = "odds_updated"
    ARBITRAGE_DETECTED = "arbitrage_detected"
    OPPORTUNITY_EXPIRED = "opportunity_expired"
    MARKET_CLOSED = "market_closed"
    BOOKMAKER_OFFLINE = "bookmaker_offline"


@dataclass
class MarketEvent:
    """Event generated by the market monitor."""
    event_type: MarketEventType
    timestamp: datetime
    bookmaker: Optional[str] = None
    sport: Optional[Sport] = None
    market_key: Optional[str] = None
    opportunity_id: Optional[UUID] = None
    data: Optional[Dict[str, Any]] = None


@dataclass
class MarketOdds:
    """Odds data for a specific market."""
    bookmaker: str
    sport: Sport
    market_type: str
    event_name: str
    odds: Dict[str, Decimal]
    confidence: float
    extracted_at: datetime
    metadata: Dict[str, Any] = field(default_factory=dict)
    
    @property
    def market_key(self) -> str:
        """Generate a unique key for this market."""
        return f"{self.sport.value}:{self.market_type}:{self.event_name}"


@dataclass
class MarketState:
    """Current state of a market."""
    market_key: str
    sport: Sport
    market_type: str
    event_name: str
    status: str = "active"
    odds_history: List[MarketOdds] = field(default_factory=list)
    arbitrage_opportunities: List[UUID] = field(default_factory=list)
    last_updated: datetime = field(default_factory=datetime.utcnow)
    metadata: Dict[str, Any] = field(default_factory=dict)
    
    @property
    def timestamp_age(self) -> float:
        """Get age of these odds in seconds."""
        return (datetime.now(timezone.utc) - self.extracted_at).total_seconds()


class ArbitrageCalculator:
    """Calculator for arbitrage opportunities."""
    
    @staticmethod
    def calculate_arbitrage(
        odds_data: Dict[str, MarketOdds],
        min_profit_margin: Decimal = Decimal('0.01')
    ) -> List[ArbitrageOpportunity]:
        """
        Calculate arbitrage opportunities from odds data.
        
        Args:
            odds_data: Dictionary of bookmaker -> MarketOdds
            min_profit_margin: Minimum profit margin to consider
            
        Returns:
            List of ArbitrageOpportunity objects
        """
        opportunities = []
        
        if len(odds_data) < 2:
            return opportunities
        
        # Get all possible outcomes from all bookmakers
        all_outcomes = set()
        for market_odds in odds_data.values():
            all_outcomes.update(market_odds.odds.keys())
        
        if len(all_outcomes) < 2:
            return opportunities
        
        # For each combination of outcomes, check for arbitrage
        outcomes_list = list(all_outcomes)
        
        # Generate all possible outcome combinations (2 to n outcomes)
        for r in range(2, len(outcomes_list) + 1):
            for outcome_combo in itertools.combinations(outcomes_list, r):
                opportunity = ArbitrageCalculator._check_outcome_combination(
                    odds_data, outcome_combo, min_profit_margin
                )
                if opportunity:
                    opportunities.append(opportunity)
        
        # Sort by profit margin (highest first)
        opportunities.sort(key=lambda x: x.profit_margin, reverse=True)
        
        return opportunities
    
    @staticmethod
    def _check_outcome_combination(
        odds_data: Dict[str, MarketOdds],
        outcomes: Tuple[str, ...],
        min_profit_margin: Decimal
    ) -> Optional[ArbitrageOpportunity]:
        """Check if a specific combination of outcomes provides arbitrage."""
        # Calculate the arbitrage percentage
        inverse_sum = Decimal('0')
        valid_bookmaker_odds = {}
        
        for outcome in outcomes:
            best_odds = Decimal('0')
            best_bookmaker = None
            
            # Find the best odds for this outcome
            for bookmaker, market_odds in odds_data.items():
                if outcome in market_odds.odds:
                    odds_value = market_odds.odds[outcome]
                    if odds_value > best_odds:
                        best_odds = odds_value
                        best_bookmaker = bookmaker
            
            if best_odds > Decimal('0'):
                inverse_sum += Decimal('1') / best_odds
                valid_bookmaker_odds[outcome] = (best_bookmaker, best_odds)
        
        # Check if we have odds for all outcomes
        if len(valid_bookmaker_odds) != len(outcomes):
            return None
        
        # Calculate profit margin
        profit_margin = (Decimal('1') / inverse_sum) - Decimal('1')
        
        if profit_margin < min_profit_margin:
            return None
        
        # Determine risk tier based on profit margin
        risk_tier = ArbitrageCalculator._determine_risk_tier(profit_margin)
        
        # Calculate stakes for guaranteed profit
        stakes = ArbitrageCalculator._calculate_optimal_stakes(
            valid_bookmaker_odds, profit_margin
        )
        
        # Create arbitrage opportunity
        return ArbitrageCalculator._create_opportunity(
            valid_bookmaker_odds, stakes, profit_margin, risk_tier
        )
    
    @staticmethod
    def _determine_risk_tier(profit_margin: Decimal) -> RiskTier:
        """Determine risk tier based on profit margin."""
        if profit_margin >= Decimal('0.10'):  # 10%+
            return RiskTier.TIER_A
        elif profit_margin >= Decimal('0.05'):  # 5%+
            return RiskTier.TIER_B
        elif profit_margin >= Decimal('0.02'):  # 2%+
            return RiskTier.TIER_C
        else:
            return RiskTier.TIER_D
    
    @staticmethod
    def _calculate_optimal_stakes(
        bookmaker_odds: Dict[str, Tuple[str, Decimal]],
        profit_margin: Decimal
    ) -> Dict[str, Decimal]:
        """Calculate optimal stake distribution for guaranteed profit."""
        total_stake = Decimal('100')  # Use 100 as base stake
        
        stakes = {}
        total_payout = total_stake * (Decimal('1') + profit_margin)
        
        for outcome, (bookmaker, odds) in bookmaker_odds.items():
            stake = total_payout / odds
            stakes[f"{bookmaker}:{outcome}"] = stake
        
        return stakes
    
    @staticmethod
    def _create_opportunity(
        bookmaker_odds: Dict[str, Tuple[str, Decimal]],
        stakes: Dict[str, Decimal],
        profit_margin: Decimal,
        risk_tier: RiskTier
    ) -> ArbitrageOpportunity:
        """Create an ArbitrageOpportunity object."""
        legs = []
        total_stake = sum(stakes.values())
        total_payout = total_stake * (Decimal('1') + profit_margin)
        
        for outcome, (bookmaker, odds) in bookmaker_odds.items():
            stake_key = f"{bookmaker}:{outcome}"
            stake = stakes[stake_key]
            
            leg = ArbitrageLeg(
                bookmaker=bookmaker,
                event_outcome=outcome,
                odds=odds,
                implied_probability=Decimal('1') / odds,
                stake_percentage=stake / total_stake,
                actual_stake=stake,
                potential_payout=stake * odds
            )
            legs.append(leg)
        
        # Determine sport and event info (this would come from the odds data)
        # For now, using placeholder values
        sport = Sport.FOOTBALL  # This should be extracted from the market data
        event_name = "Arbitrage Opportunity"  # This should be extracted from market data
        
        return ArbitrageOpportunity(
            sport=sport,
            event_name=event_name,
            event_date=datetime.now(timezone.utc) + timedelta(hours=1),
            market_type="arbitrage",
            legs=legs,
            total_stake=total_stake,
            profit_margin=profit_margin,
            profit_amount=total_stake * profit_margin,
            risk_tier=risk_tier,
            source_scanner="market_monitor"
        )


