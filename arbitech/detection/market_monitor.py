class MarketMonitor:
    """
    Market state tracking system that maintains current odds across bookmakers
    and detects arbitrage opportunities in real-time.
    """
    
    def __init__(self, config: Optional[Dict[str, Any]] = None):
        """
        Initialize the market monitor.
        
        Args:
            config: Monitor configuration
        """
        self.config = config or {}
        self.logger = logging.getLogger(__name__)
        
        # Configuration
        self.max_odds_age = self.config.get('max_odds_age_seconds', 300)
        self.min_confidence = self.config.get('min_confidence', 0.7)
        self.opportunity_expiry_minutes = self.config.get('opportunity_expiry_minutes', 15)
        self.max_bookmaker_age = self.config.get('max_bookmaker_age_seconds', 600)
        
        # Market state
        self.current_odds: Dict[str, Dict[str, MarketOdds]] = defaultdict(dict)
        self.discovered_opportunities: Dict[UUID, ArbitrageOpportunity] = {}
        self.expired_opportunities: deque = deque(maxlen=1000)
        self.bookmaker_status: Dict[str, Dict[str, Any]] = defaultdict(dict)
        
        # Performance optimization
        self.market_cache: Dict[str, Any] = {}
        self.last_cleanup = datetime.now(timezone.utc)
        self.cleanup_interval = 300  # 5 minutes
        
        # Threading
        self._lock = RLock()
        self._running = False
        self._event_handlers: List[Callable[[MarketEvent], None]] = []
        
        # Background tasks
        self._cleanup_task: Optional[asyncio.Task] = None
        self._expiry_task: Optional[asyncio.Task] = None
        
        self.logger.info("MarketMonitor initialized")
    
    async def start(self):
        """Start the market monitor."""
        if self._running:
            self.logger.warning("MarketMonitor already running")
            return
        
        self._running = True
        
        # Start background tasks
        self._cleanup_task = asyncio.create_task(self._cleanup_loop())
        self._expiry_task = asyncio.create_task(self._expiry_loop())
        
        self.logger.info("MarketMonitor started")
    
    async def stop(self):
        """Stop the market monitor."""
        if not self._running:
            return
        
        self.logger.info("Stopping MarketMonitor...")
        
        self._running = False
        
        # Cancel background tasks
        if self._cleanup_task:
            self._cleanup_task.cancel()
        
        if self._expiry_task:
            self._expiry_task.cancel()
        
        # Wait for tasks to complete
        tasks = [t for t in [self._cleanup_task, self._expiry_task] if t]
        if tasks:
            await asyncio.gather(*tasks, return_exceptions=True)
        
        self.logger.info("MarketMonitor stopped")
    
    async def update_market_odds(self, odds_data: Dict[str, Any]) -> bool:
        """
        Update odds for a specific market.
        
        Args:
            odds_data: Dictionary containing odds information
            
        Returns:
            True if this update could create new arbitrage opportunities
        """
        try:
            # Extract data
            bookmaker = odds_data['bookmaker']
            sport = odds_data['sport']
            market_type = odds_data['market_type']
            odds = odds_data['odds']
            confidence = odds_data['confidence']
            extracted_at = odds_data.get('extracted_at', datetime.now(timezone.utc))
            
            # Validate confidence
            if confidence < self.min_confidence:
                self.logger.debug(
                    "Skipping odds update from %s due to low confidence: %.2f",
                    bookmaker, confidence
                )
                return False
            
            # Create MarketOdds object
            market_odds = MarketOdds(
                bookmaker=bookmaker,
                sport=sport,
                market_type=market_type,
                event_name=odds_data.get('event_name', f"{sport.value} event"),
                odds=odds,
                confidence=confidence,
                extracted_at=extracted_at,
                metadata=odds_data.get('metadata', {})
            )
            
            # Update bookmaker status
            self.bookmaker_status[bookmaker]['last_update'] = extracted_at
            self.bookmaker_status[bookmaker]['status'] = 'active'
            
            # Store odds data
            market_key = market_odds.market_key
            with self._lock:
                self.current_odds[market_key][bookmaker] = market_odds
            
            # Emit event
            await self._emit_event(MarketEvent(
                event_type=MarketEventType.ODDS_UPDATED,
                timestamp=datetime.now(timezone.utc),
                bookmaker=bookmaker,
                sport=sport,
                market_key=market_key
            ))
            
            # Check for arbitrage opportunities
            return await self._check_arbitrage_for_market(market_key)
            
        except Exception as e:
            self.logger.error("Error updating market odds: %s", str(e))
            return False
    
    async def find_arbitrage_opportunities(
        self,
        min_profit_margin: Optional[Decimal] = None,
        sport: Optional[Sport] = None,
        risk_tier: Optional[RiskTier] = None,
        limit: int = 100
    ) -> List[ArbitrageOpportunity]:
        """
        Find arbitrage opportunities across all markets.
        
        Args:
            min_profit_margin: Minimum profit margin
            sport: Filter by sport
            risk_tier: Filter by risk tier
            limit: Maximum number of opportunities to return
            
        Returns:
            List of ArbitrageOpportunity objects
        """
        opportunities = []
        
        # Use default minimum profit margin if not specified
        if min_profit_margin is None:
            min_profit_margin = Decimal('0.01')  # 1%
        
        with self._lock:
            for market_key, bookmaker_odds in self.current_odds.items():
                # Filter by sport if specified
                if sport:
                    market_sport = list(bookmaker_odds.values())[0].sport
                    if market_sport != sport:
                        continue
                
                # Check for arbitrage opportunities
                market_opportunities = ArbitrageCalculator.calculate_arbitrage(
                    bookmaker_odds, min_profit_margin
                )
                
                # Filter by risk tier if specified
                if risk_tier:
                    market_opportunities = [
                        opp for opp in market_opportunities 
                        if opp.risk_tier == risk_tier
                    ]
                
                opportunities.extend(market_opportunities)
        
        # Sort by profit margin and limit results
        opportunities.sort(key=lambda x: x.profit_margin, reverse=True)
        return opportunities[:limit]
    
    def get_opportunities(
        self,
        min_profit_margin: Optional[Decimal] = None,
        sport: Optional[Sport] = None,
        risk_tier: Optional[RiskTier] = None,
        limit: int = 100
    ) -> List[ArbitrageOpportunity]:
        """Get discovered arbitrage opportunities."""
        opportunities = list(self.discovered_opportunities.values())
        
        # Apply filters
        if min_profit_margin:
            opportunities = [opp for opp in opportunities if opp.profit_margin >= min_profit_margin]
        
        if sport:
            opportunities = [opp for opp in opportunities if opp.sport == sport]
        
        if risk_tier:
            opportunities = [opp for opp in opportunities if opp.risk_tier == risk_tier]
        
        # Sort by profit margin and limit
        opportunities.sort(key=lambda x: x.profit_margin, reverse=True)
        return opportunities[:limit]
    
    def get_market_state(self, market_key: str) -> Optional[Dict[str, Any]]:
        """Get the current state of a specific market."""
        with self._lock:
            if market_key in self.current_odds:
                bookmaker_odds = self.current_odds[market_key]
                
                return {
                    'market_key': market_key,
                    'bookmakers': list(bookmaker_odds.keys()),
                    'last_update': max(
                        odds.extracted_at for odds in bookmaker_odds.values()
                    ).isoformat(),
                    'odds_count': len(bookmaker_odds),
                    'outcomes': list(set().union(*[odds.odds.keys() for odds in bookmaker_odds.values()])),
                    'average_confidence': sum(
                        odds.confidence for odds in bookmaker_odds.values()
                    ) / len(bookmaker_odds)
                }
        
        return None
    
    def get_state_summary(self) -> Dict[str, Any]:
        """Get a summary of the current market state."""
        with self._lock:
            total_markets = len(self.current_odds)
            total_bookmakers = len(self.bookmaker_status)
            total_opportunities = len(self.discovered_opportunities)
            
            # Calculate market statistics
            market_stats = defaultdict(int)
            sport_stats = defaultdict(int)
            
            for market_key, bookmaker_odds in self.current_odds.items():
                sport = list(bookmaker_odds.values())[0].sport
                sport_stats[sport.value] += 1
                market_stats[list(bookmaker_odds.values())[0].market_type] += 1
            
            # Bookmaker statistics
            active_bookmakers = 0
            for bookmaker, status in self.bookmaker_status.items():
                if status.get('status') == 'active':
                    active_bookmakers += 1
            
            return {
                'total_markets': total_markets,
                'total_bookmakers': total_bookmakers,
                'active_bookmakers': active_bookmakers,
                'total_opportunities': total_opportunities,
                'market_types': dict(market_stats),
                'sports_distribution': dict(sport_stats),
                'bookmaker_status': {
                    name: {
                        'status': status.get('status', 'unknown'),
                        'last_update': status.get('last_update', datetime.min).isoformat()
                    }
                    for name, status in self.bookmaker_status.items()
                },
                'average_confidence': self._calculate_average_confidence()
            }
    
    def _calculate_average_confidence(self) -> float:
        """Calculate average confidence across all odds."""
        all_confidences = []
        
        with self._lock:
            for bookmaker_odds in self.current_odds.values():
                for odds in bookmaker_odds.values():
                    all_confidences.append(odds.confidence)
        
        return sum(all_confidences) / len(all_confidences) if all_confidences else 0.0
    
    async def _check_arbitrage_for_market(self, market_key: str) -> bool:
        """Check for arbitrage opportunities in a specific market."""
        try:
            with self._lock:
                if market_key not in self.current_odds:
                    return False
                
                bookmaker_odds = self.current_odds[market_key]
            
            # Calculate arbitrage opportunities
            opportunities = ArbitrageCalculator.calculate_arbitrage(bookmaker_odds)
            
            # Store new opportunities
            new_opportunities_found = False
            for opportunity in opportunities:
                # Check if we already have this opportunity
                existing = self._find_similar_opportunity(opportunity)
                
                if not existing:
                    self.discovered_opportunities[opportunity.id] = opportunity
                    new_opportunities_found = True
                    
                    # Emit event
                    await self._emit_event(MarketEvent(
                        event_type=MarketEventType.ARBITRAGE_DETECTED,
                        timestamp=datetime.now(timezone.utc),
                        sport=opportunity.sport,
                        market_key=market_key,
                        opportunity_id=opportunity.id,
                        data={'profit_margin': float(opportunity.profit_margin)}
                    ))
            
            return new_opportunities_found
            
        except Exception as e:
            self.logger.error("Error checking arbitrage for market %s: %s", market_key, str(e))
            return False
    
    def _find_similar_opportunity(self, opportunity: ArbitrageOpportunity) -> Optional[ArbitrageOpportunity]:
        """Find a similar existing opportunity to avoid duplicates."""
        for existing in self.discovered_opportunities.values():
            if (
                existing.sport == opportunity.sport and
                existing.event_name == opportunity.event_name and
                existing.market_type == opportunity.market_type and
                abs(float(existing.profit_margin - opportunity.profit_margin)) < 0.001
            ):
                return existing
        
        return None
    
    async def _cleanup_loop(self):
        """Background task to clean up old data."""
        try:
            while self._running:
                await asyncio.sleep(self.cleanup_interval)
                await self._perform_cleanup()
        except asyncio.CancelledError:
            pass
    
    async def _expiry_loop(self):
        """Background task to expire old opportunities."""
        try:
            while self._running:
                await asyncio.sleep(60)  # Check every minute
                await self._expire_opportunities()
        except asyncio.CancelledError:
            pass
    
    async def _perform_cleanup(self):
        """Perform cleanup of old data."""
        try:
            current_time = datetime.now(timezone.utc)
            
            with self._lock:
                # Clean up old odds
                expired_markets = []
                for market_key, bookmaker_odds in self.current_odds.items():
                    for bookmaker, odds in list(bookmaker_odds.items()):
                        age = (current_time - odds.extracted_at).total_seconds()
                        if age > self.max_odds_age:
                            del bookmaker_odds[bookmaker]
                    
                    # Remove markets with no odds
                    if not bookmaker_odds:
                        expired_markets.append(market_key)
                
                for market_key in expired_markets:
                    del self.current_odds[market_key]
                
                # Clean up bookmaker status
                expired_bookmakers = []
                for bookmaker, status in self.bookmaker_status.items():
                    last_update = status.get('last_update', datetime.min)
                    age = (current_time - last_update).total_seconds()
                    if age > self.max_bookmaker_age:
                        expired_bookmakers.append(bookmaker)
                
                for bookmaker in expired_bookmakers:
                    del self.bookmaker_status[bookmaker]
            
            self.last_cleanup = current_time
            self.logger.debug("Performed market cleanup")
            
        except Exception as e:
            self.logger.error("Error during cleanup: %s", str(e))
    
    async def _expire_opportunities(self):
        """Expire old arbitrage opportunities."""
        try:
            current_time = datetime.now(timezone.utc)
            expired_opportunities = []
            
            with self._lock:
                for opp_id, opportunity in self.discovered_opportunities.items():
                    age_minutes = (current_time - opportunity.discovered_at).total_seconds() / 60
                    
                    if age_minutes > self.opportunity_expiry_minutes:
                        expired_opportunities.append(opp_id)
                
                # Remove expired opportunities
                for opp_id in expired_opportunities:
                    opportunity = self.discovered_opportunities.pop(opp_id)
                    self.expired_opportunities.append(opportunity)
                    
                    # Emit event
                    asyncio.create_task(self._emit_event(MarketEvent(
                        event_type=MarketEventType.OPPORTUNITY_EXPIRED,
                        timestamp=current_time,
                        opportunity_id=opp_id
                    )))
            
            if expired_opportunities:
                self.logger.info("Expired %d arbitrage opportunities", len(expired_opportunities))
            
        except Exception as e:
            self.logger.error("Error expiring opportunities: %s", str(e))
    
    def add_event_handler(self, handler: Callable[[MarketEvent], None]):
        """Add an event handler for market events."""
        self._event_handlers.append(handler)
    
    async def _emit_event(self, event: MarketEvent):
        """Emit a market event to all handlers."""
        for handler in self._event_handlers:
            try:
                if asyncio.iscoroutinefunction(handler):
                    await handler(event)
                else:
                    handler(event)
            except Exception as e:
                self.logger.error("Error in market event handler: %s", str(e))
    
    def to_dict(self) -> Dict[str, Any]:
        """Convert market monitor state to dictionary."""
        return {
            'current_odds': {
                market_key: {
                    bookmaker: {
                        'sport': odds.sport.value,
                        'market_type': odds.market_type,
                        'event_name': odds.event_name,
                        'odds': {k: float(v) for k, v in odds.odds.items()},
                        'confidence': odds.confidence,
                        'extracted_at': odds.extracted_at.isoformat(),
                        'metadata': odds.metadata
                    }
                    for bookmaker, odds in bookmaker_odds.items()
                }
                for market_key, bookmaker_odds in self.current_odds.items()
            },
            'discovered_opportunities': {
                str(opp_id): opp.dict()
                for opp_id, opp in self.discovered_opportunities.items()
            },
            'summary': self.get_state_summary()
        }


