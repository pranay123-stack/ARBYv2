async def create_market_monitor(
    config: Optional[Dict[str, Any]] = None
) -> MarketMonitor:
    """
    Create and configure a market monitor.
    
    Args:
        config: Optional configuration override
        
    Returns:
        Configured MarketMonitor instance
    """
    monitor = MarketMonitor(config)
    
    # Add default event handlers
    monitor.add_event_handler(_default_market_event_handler)
    
    return monitor


async def _default_market_event_handler(event: MarketEvent):
    """Default event handler for logging market events."""
    logger = logging.getLogger(__name__)
    
    if event.event_type == MarketEventType.ARBITRAGE_DETECTED:
        profit_margin = event.data.get('profit_margin', 0) if event.data else 0
        logger.info(
            "🎯 Arbitrage opportunity detected! Sport: %s, Market: %s, Margin: %.2f%%",
            event.sport.value if event.sport else "unknown",
            event.market_key,
            profit_margin * 100
        )
    elif event.event_type == MarketEventType.ODDS_UPDATED:
        logger.debug(
            "Odds updated - Bookmaker: %s, Sport: %s",
            event.bookmaker,
            event.sport.value if event.sport else "unknown"
        )


